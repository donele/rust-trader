use std::cmp::Ordering;
use std::collections::BinaryHeap;

use core::{Message, OrderRequest, TimeNanos};

use crate::SimSequencer;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EventTarget {
    Exchange,
    Client,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum EventPayload {
    Message(Message),
    OrderRequest(OrderRequest),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ScheduledEvent {
    pub delivery_time: TimeNanos,
    pub priority: i64,
    pub sequence: u64,
    pub target: EventTarget,
    pub payload: EventPayload,
}

#[derive(Debug, Clone, Copy, PartialEq)]
struct QueueEntry(ScheduledEvent);

impl Eq for QueueEntry {}

impl Ord for QueueEntry {
    fn cmp(&self, other: &Self) -> Ordering {
        other
            .0
            .delivery_time
            .cmp(&self.0.delivery_time)
            .then_with(|| other.0.priority.cmp(&self.0.priority))
            .then_with(|| other.0.sequence.cmp(&self.0.sequence))
    }
}

impl PartialOrd for QueueEntry {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

/// Global runtime event coordinator.
///
/// Source events are merged by [`SimSequencer`]. Runtime events generated by
/// the exchange or client are merged with that source stream here. Every
/// event carries a target so exchange-bound orders cannot be consumed by the
/// client and client-bound updates cannot re-enter the exchange.
#[derive(Debug)]
pub struct SimulationEventQueue {
    sources: SimSequencer,
    scheduled: BinaryHeap<QueueEntry>,
    next_sequence: u64,
}

impl SimulationEventQueue {
    pub fn new(sources: SimSequencer) -> Self {
        Self {
            sources,
            scheduled: BinaryHeap::new(),
            next_sequence: 0,
        }
    }

    pub fn push_client_message(
        &mut self,
        delivery_time: TimeNanos,
        priority: i64,
        message: Message,
    ) {
        let sequence = self.take_sequence();
        self.push(ScheduledEvent {
            delivery_time,
            priority,
            sequence,
            target: EventTarget::Client,
            payload: EventPayload::Message(message),
        });
    }

    pub fn push_exchange_order(
        &mut self,
        delivery_time: TimeNanos,
        priority: i64,
        request: OrderRequest,
    ) {
        let sequence = self.take_sequence();
        self.push(ScheduledEvent {
            delivery_time,
            priority,
            sequence,
            target: EventTarget::Exchange,
            payload: EventPayload::OrderRequest(request),
        });
    }

    pub fn next_event(&mut self) -> Option<ScheduledEvent> {
        let source_message = self.sources.peek_next_message();
        let scheduled_event = self.scheduled.peek().map(|entry| entry.0);

        match (source_message, scheduled_event) {
            (None, None) => None,
            (Some(_), None) => self.next_source_event(),
            (None, Some(_)) => self.scheduled.pop().map(|entry| entry.0),
            (Some(message), Some(event)) if message.ts_nanos() <= event.delivery_time => {
                self.next_source_event()
            }
            (Some(_), Some(_)) => self.scheduled.pop().map(|entry| entry.0),
        }
    }

    fn next_source_event(&mut self) -> Option<ScheduledEvent> {
        let message = self.sources.next_message()?;
        let target = if matches!(message, Message::AlgoOrderRequest(_)) {
            EventTarget::Client
        } else {
            EventTarget::Exchange
        };
        Some(ScheduledEvent {
            delivery_time: message.ts_nanos(),
            priority: 0,
            sequence: self.take_sequence(),
            target,
            payload: EventPayload::Message(message),
        })
    }

    fn push(&mut self, event: ScheduledEvent) {
        self.scheduled.push(QueueEntry(event));
    }

    fn take_sequence(&mut self) -> u64 {
        let sequence = self.next_sequence;
        self.next_sequence += 1;
        sequence
    }
}

#[cfg(test)]
mod tests {
    use core::{BookTicker, Message, SymbolId};

    use super::*;

    fn ticker(timestamp: i64) -> Message {
        Message::BookTicker(BookTicker {
            ts_nanos: timestamp,
            symbol: SymbolId(1),
            best_bid_price: 100.0,
            best_bid_qty: 1.0,
            best_ask_price: 101.0,
            best_ask_qty: 1.0,
            update_id: timestamp as u64,
        })
    }

    #[test]
    fn source_events_go_to_exchange_before_client_delivery() {
        let message = ticker(10);
        let mut queue = SimulationEventQueue::new(SimSequencer::new(vec![message]));

        let exchange_event = queue.next_event().unwrap();
        assert_eq!(exchange_event.target, EventTarget::Exchange);
        assert_eq!(exchange_event.payload, EventPayload::Message(message));

        queue.push_client_message(10, 0, message);
        let client_event = queue.next_event().unwrap();
        assert_eq!(client_event.target, EventTarget::Client);
        assert_eq!(client_event.payload, EventPayload::Message(message));
    }
}
